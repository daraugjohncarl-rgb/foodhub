#!/usr/bin/env python3
"""
Render the SQLAlchemy models as an idempotent PostgreSQL baseline migration (no database needed).

    python scripts/generate_baseline_sql.py > ../supabase/migrations/<timestamp>_baseline_schema.sql

Every statement is IF NOT EXISTS, so applying it to a database that was originally built by
Base.metadata.create_all() (the current Supabase project) is a no-op, while an empty database
receives the full schema.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("DATABASE_URL", "sqlite://")  # only to import the models; nothing connects

from sqlalchemy import Enum
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.db import Base
import app.models  # noqa: F401  (registers tables)

dialect = postgresql.dialect()
out = [
    "-- Baseline schema generated from app/models.py (PostgreSQL / Supabase).",
    "-- Idempotent: safe to apply to a database that already has these objects.",
    "-- Generated by fastapi/scripts/generate_baseline_sql.py -- do not edit by hand.",
    "",
]

# Enum types (CREATE TYPE has no IF NOT EXISTS)
seen = set()
for table in Base.metadata.sorted_tables:
    for column in table.columns:
        if isinstance(column.type, Enum) and column.type.name not in seen:
            seen.add(column.type.name)
            labels = ", ".join("'%s'" % label.replace("'", "''") for label in column.type.enums)
            out += [
                "DO $$ BEGIN",
                f"    CREATE TYPE {column.type.name} AS ENUM ({labels});",
                "EXCEPTION WHEN duplicate_object THEN NULL;",
                "END $$;",
                "",
            ]

for table in Base.metadata.sorted_tables:
    out.append(str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
    out.append("")
    for index in sorted(table.indexes, key=lambda i: i.name):
        out.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
    out.append("")

print("\n".join(out))
