function openProduct(index) {

    selectedProduct = menu[index];
    selectedVariant = 0;
    selectedQuantity = 1;

    productOverlay.classList.add("active");
    document.body.classList.add("modal-open");

    detailImage.innerHTML = productImage(selectedProduct);
    detailTitle.textContent = selectedProduct.name;
    detailDescription.textContent = selectedProduct.description;

    renderVariants();
    updateProduct();

}


function closeProduct() {

    productOverlay.classList.remove("active");
    document.body.classList.remove("modal-open");

}


function renderVariants() {

    if (selectedProduct.options.length <= 1) {

        variantSection.style.display = "none";
        variantList.innerHTML = "";

        return;
    }

    variantSection.style.display = "block";

    variantList.innerHTML = selectedProduct.options
        .map((option, index) => `

            <label class="variant-option">

                <input
                    type="radio"
                    name="variant"
                    value="${index}"
                    ${index === selectedVariant ? "checked" : ""}
                >

                <span>
                    ${escapeHTML(option[0])}
                </span>

                <strong>
                    ${peso(option[1])}
                </strong>

            </label>

        `)
        .join("");

    variantList.querySelectorAll("input")
        .forEach(input => {
            input.addEventListener(
                "change",
                () => {
                    selectedVariant =
                        Number(input.value);

                    updateProduct();
                }
            );
        });

}


function updateProduct() {

    const price =
        selectedProduct.options[selectedVariant][1];

    detailPrice.textContent = peso(price);
    quantityValue.textContent = selectedQuantity;
    detailTotal.textContent =
        peso(price * selectedQuantity);

}


