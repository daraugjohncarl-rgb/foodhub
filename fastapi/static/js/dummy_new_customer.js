function addToCart() {

    const option =
        selectedProduct.options[selectedVariant];

    const existing = cart.find(item =>
        item.name === selectedProduct.name &&
        item.variant === option[0]
    );

    if (existing) {
        existing.quantity += selectedQuantity;
    } else {
        cart.push({
            name: selectedProduct.name,
            variant: option[0],
            price: option[1],
            quantity: selectedQuantity
        });
    }

    closeProduct();
    updateCart();
    showToast("Added to cart");

}


function updateCart() {

    const count = cart.reduce(
        (sum, item) => sum + item.quantity,
        0
    );

    const total = cart.reduce(
        (sum, item) =>
            sum + item.price * item.quantity,
        0
    );

    cartCount.textContent = count;
    floatingItems.textContent =
        count + (count === 1 ? " item" : " items");
    floatingTotal.textContent = peso(total);

    if (count > 0) {
        document
            .getElementById("floatingCart")
            .classList.add("active");
    } else {
        document
            .getElementById("floatingCart")
            .classList.remove("active");
    }

    renderCart();

}


function renderCart() {

    if (cart.length === 0) {
        cartList.innerHTML = `
            <div class="empty-cart">
                Your cart is empty.
            </div>
        `;

        cartTotal.textContent = peso(0);

        return;
    }

    cartList.innerHTML = cart
        .map((item, index) => `

            <div class="cart-item">

                <div class="cart-item-info">

                    <strong>
                        ${escapeHTML(item.name)}
                    </strong>

                    <span>
                        ${escapeHTML(item.variant)}
                    </span>

                    <small>
                        ${peso(item.price)} each
                    </small>

                </div>

                <div class="cart-item-actions">

                    <button
                        type="button"
                        data-action="decrease"
                        data-index="${index}"
                    >
                        −
                    </button>

                    <span>
                        ${item.quantity}
                    </span>

                    <button
                        type="button"
                        data-action="increase"
                        data-index="${index}"
                    >
                        +
                    </button>

                </div>

                <strong class="cart-item-total">
                    ${peso(item.price * item.quantity)}
                </strong>

            </div>

        `)
        .join("");

    const total = cart.reduce(
        (sum, item) =>
            sum + item.price * item.quantity,
        0
    );

    cartTotal.textContent = peso(total);

    cartList.querySelectorAll("button")
        .forEach(button => {
            button.addEventListener(
                "click",
                () => {
                    const index =
                        Number(button.dataset.index);

                    const action =
                        button.dataset.action;

                    if (action === "increase") {
                        cart[index].quantity++;
                    } else {
                        cart[index].quantity--;

                        if (cart[index].quantity <= 0) {
                            cart.splice(index, 1);
                        }
                    }

                    updateCart();
                }
            );
        });

}


