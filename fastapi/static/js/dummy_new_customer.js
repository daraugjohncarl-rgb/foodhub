/* =========================================================
   PESO FORMAT
========================================================= */

function peso(value) {

    return "₱" +
        Number(value).toLocaleString(
            "en-PH",
            {
                minimumFractionDigits: 2,
                maximumFractionDigits: 2
            }
        );

}


/* =========================================================
   ESCAPE HTML
========================================================= */

function escapeHTML(value) {

    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");

}


/* =========================================================
   PRODUCT IMAGE
========================================================= */

function productImage(product) {

    return `

        <img
            src="${product.image}"
            alt="${escapeHTML(product.name)}"
            onerror="
                this.style.display='none';
                this.parentElement
                    .querySelector('.image-placeholder')
                    .style.display='flex';
            "
        >

        <div
            class="image-placeholder"
            style="display:none;"
        >
            ${escapeHTML(product.name)}
        </div>

    `;

}


/* =========================================================
   FILTER
========================================================= */

function getFilteredProducts() {

    return menu.filter(product => {

        const categoryMatch =
            activeCategory === "All" ||
            product.category === activeCategory;

        const searchable = (
            product.name +
            " " +
            product.category +
            " " +
            product.description +
            " " +
            product.options
                .map(option => option[0])
                .join(" ")
        ).toLowerCase();

        const searchMatch =
            searchable.includes(
                searchTerm.toLowerCase()
            );

        return categoryMatch &&
            searchMatch;
    });

}


/* =========================================================
   RENDER MENU
========================================================= */

function renderMenu() {

    const products =
        getFilteredProducts();

    menuList.innerHTML = products
        .map((product, index) => {

            const originalIndex =
                menu.indexOf(product);

            const prices =
                product.options.map(option => option[1]);

            const lowest =
                Math.min(...prices);

            const highest =
                Math.max(...prices);

            let priceText;

            if (lowest === highest) {
                priceText = peso(lowest);
            } else {
                priceText =
                    peso(lowest) +
                    " - " +
                    peso(highest);
            }

            return `

                <article
                    class="menu-item"
                    data-index="${originalIndex}"
                >

                    <div class="menu-image">
                        ${productImage(product)}
                    </div>

                    <div class="menu-info">

                        <div class="menu-category">
                            ${escapeHTML(product.category)}
                        </div>

                        <div class="menu-name">
                            ${escapeHTML(product.name)}
                        </div>

                        <div class="menu-description">
                            ${escapeHTML(product.description)}
                        </div>

                        <div class="menu-bottom">

                            <div class="menu-price">
                                ${priceText}
                            </div>

                            <button
                                class="select-button"
                                type="button"
                                data-index="${originalIndex}"
                            >
                                Select
                            </button>

                        </div>

                    </div>

                </article>

            `;
        })
        .join("");

    menuCount.textContent =
        products.length +
        (products.length === 1 ? " item" : " items");

    menuList.querySelectorAll(".menu-item")
        .forEach(card => {
            card.addEventListener(
                "click",
                event => {
                    if (event.target.closest(".select-button")) {
                        return;
                    }

                    openProduct(
                        Number(card.dataset.index)
                    );
                }
            );
        });

    menuList.querySelectorAll(".select-button")
        .forEach(button => {
            button.addEventListener(
                "click",
                () => {
                    openProduct(
                        Number(button.dataset.index)
                    );
                }
            );
        });

}


